def main():
    rows = list(csv.DictReader(io.open(SRC, encoding='utf-8-sig')))
    recs = []
    for r in rows:
        name = (r['city'] or r['settlement'] or '').strip()
        if not name and (r['region_type'] or '').strip() in ('г', 'гор'):
            name = (r['region'] or '').strip()      # Москва, Санкт-Петербург, Севастополь
        if not name:
            continue
        try:
            lat, lon = round(float(r['geo_lat']), 3), round(float(r['geo_lon']), 3)
        except ValueError:
            continue
        region = (r['region'] or '').strip()
        okrug = OKRUG.get((r['federal_district'] or '').strip(), '')
        pop = int(r['population'] or 0)
        if name in PORTS:
            kind = 'порт'
        elif (r['city_type'] or '').strip() == 'г' or (r['region_type'] or '').strip() in ('г', 'гор'):
            kind = 'город'
        else:
            kind = 'посёлок'
        recs.append((name, region, okrug, lat, lon, pop, kind))
    have = {x[0] for x in recs}
    for name, region, okrug, lat, lon, pop, kind in SUPPLEMENT:
        if name not in have:
            recs.append((name, region, okrug, lat, lon, pop, kind))
    recs.sort(key=lambda x: -x[5])

    regions = sorted({x[1] for x in recs})
    oks = ['ЦФО', 'СЗФО', 'ЮФО', 'СКФО', 'ПФО', 'УФО', 'СФО', 'ДФО', '']
    js = ('/* ============================================================\n'
          '   База населённых пунктов России: %d городов, посёлков, портов, терминалов и\n'
          '   пунктов пропуска с координатами, регионами и населением (открытый набор данных;\n'
          '   дополняется записями из таблицы settlements в базе платформы).\n'
          '   Пересобирается скриптом tools/build_settlements.py.\n'
          '   Формат записи: [название, индекс региона, индекс округа, широта, долгота, население, индекс типа]\n'
          '   ============================================================ */\n' % len(recs))
    js += 'const SETTLEMENTS_REGIONS = ' + json.dumps(regions, ensure_ascii=False) + ';\n'
    js += 'const SETTLEMENTS_OKRUGS = ' + json.dumps(oks, ensure_ascii=False) + ';\n'
    js += 'const SETTLEMENTS_KINDS = ' + json.dumps(KINDS, ensure_ascii=False) + ';\n'
    js += 'const SETTLEMENTS = [\n'
    js += ',\n'.join('  ' + json.dumps([n, regions.index(reg), oks.index(ok), lat, lon, pop, KINDS.index(k)], ensure_ascii=False).replace(' ', '')
                    for n, reg, ok, lat, lon, pop, k in recs)
    js += '\n];\n'
    io.open(OUT, 'w', encoding='utf-8').write(js)
    print('записей: %d | регионов: %d | размер: %.1f КБ' % (len(recs), len(regions), len(js.encode()) / 1024))
    for probe in ('Москва', 'Санкт-Петербург', 'Новороссийск', 'Усть-Луга', 'Верхний Ларс', 'Сабетта'):
        print('  ', probe, '→', 'есть' if any(x[0] == probe for x in recs) else 'НЕТ')


if __name__ == '__main__':
    main()
